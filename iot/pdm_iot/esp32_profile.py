"""P2.5 — export a dataset-grounded synthetic profile for the ESP32 (docs/05 §10).

Writes two files with the SAME numbers:
  iot/esp32/include/profile_fd001.h   (compiled into the firmware)
  iot/esp32/profile_fd001.json        (read by the virtual ESP32, so both generate identical streams)

Modes:
  TRAJECTORY   replay one real *test* engine (unseen by the model) with small Gaussian noise added
  DISTRIBUTION sample a lifetime from the training-life distribution and generate each sensor as
               healthy mean + mean degradation drift D(remaining cycles) + measurement noise

    pdm-export-esp32-profile --profile FD001
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path
from typing import Any

import numpy as np

from pdm_ml.config import find_root, raw_dir
from pdm_ml.io.loader import load_split, load_true_rul, sensor_symbols
from pdm_ml.labels.rul import train_rul

SETTINGS = ["setting_1", "setting_2", "setting_3"]
DRIFT_GRID = list(range(0, 130, 5))  # remaining cycles 0..125
NOISE_SCALE_TRAJECTORY = 0.25
VERSION = "1.0.0"


def _sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()[:16]


def choose_unit(profile: str, min_len: int = 100) -> int:
    """Unseen test engine that ends closest to failure (so the stream reaches Critical) with >= min_len cycles."""
    test = load_split(profile, "test")
    rul = load_true_rul(profile)
    lens = test.groupby("unit").cycle.max()
    cand = rul[lens.loc[rul.index] >= min_len]
    return int(cand.idxmin())


def build_profile(profile: str, unit: int | None = None) -> dict[str, Any]:
    if profile not in ("FD001", "FD003"):
        raise ValueError("ESP32 synthetic profiles support single-condition FD001/FD003 only")
    sensors = sensor_symbols()
    channels = SETTINGS + sensors
    train = load_split(profile, "train")
    test = load_split(profile, "test")
    unit = unit or choose_unit(profile)
    traj = test[test.unit == unit][channels].to_numpy(float)
    true_rul_end = int(load_true_rul(profile).loc[unit])

    rul = train_rul(train)
    healthy = train[rul >= 125]
    mu0 = healthy[channels].mean().to_numpy()
    # measurement noise: residual of a centred rolling mean, healthy phase
    resid = healthy.groupby("unit")[channels].transform(lambda s: s - s.rolling(9, center=True, min_periods=1).mean())
    sigma = resid.std().fillna(0).to_numpy()
    # mean drift by remaining cycles
    drift = np.zeros((len(DRIFT_GRID), len(channels)))
    for i, r in enumerate(DRIFT_GRID):
        rows = train[(rul >= r - 2) & (rul <= r + 2)]
        drift[i] = rows[channels].mean().to_numpy() - mu0
    drift[:, :3] = 0.0  # settings do not degrade
    const = [c for c in channels if train[c].nunique() == 1]
    for c in const:
        j = channels.index(c)
        drift[:, j], sigma[j] = 0.0, 0.0
    lives = np.log(train.groupby("unit").cycle.max().to_numpy(float))
    return {
        "profile": profile,
        "version": VERSION,
        "data_sha": _sha(raw_dir() / f"train_{profile}.txt") + _sha(raw_dir() / f"test_{profile}.txt"),
        "channels": channels,
        "n_settings": 3,
        "trajectory_unit": unit,
        "trajectory_true_rul_end": true_rul_end,
        "trajectory": np.round(traj, 4).tolist(),
        "noise_scale_trajectory": NOISE_SCALE_TRAJECTORY,
        "healthy_mean": np.round(mu0, 5).tolist(),
        "noise_sigma": np.round(sigma, 5).tolist(),
        "drift_grid": DRIFT_GRID,
        "drift": np.round(drift, 5).tolist(),
        "life_log_mean": round(float(lives.mean()), 5),
        "life_log_std": round(float(lives.std()), 5),
        "life_min": int(np.exp(lives.min())),
    }


def _c_array(name: str, values: list[float], per_line: int = 8) -> str:
    items = [f"{v:.5f}f" for v in values]
    lines = [", ".join(items[i:i + per_line]) for i in range(0, len(items), per_line)]
    return f"static const float {name}[{len(values)}] = {{\n  " + ",\n  ".join(lines) + "\n};\n"


def render_header(p: dict[str, Any]) -> str:
    n = len(p["channels"])
    flat_traj = [v for row in p["trajectory"] for v in row]
    flat_drift = [v for row in p["drift"] for v in row]
    names = ", ".join(f'"{c}"' for c in p["channels"])
    guard = f"PDM_PROFILE_{p['profile']}_H"
    return f"""// GENERATED by `pdm-export-esp32-profile --profile {p['profile']}` — do not edit.
// Source: NASA C-MAPSS {p['profile']} (data sha {p['data_sha']}). Profile version {p['version']}.
// TRAJECTORY = test unit {p['trajectory_unit']} ({len(p['trajectory'])} cycles, true RUL at end {p['trajectory_true_rul_end']}).
#ifndef {guard}
#define {guard}

#define PDM_PROFILE_NAME "{p['profile']}"
#define PDM_PROFILE_VERSION "{p['version']}"
#define PDM_PROFILE_DATA_SHA "{p['data_sha']}"
#define PDM_N_CHANNELS {n}
#define PDM_N_SETTINGS {p['n_settings']}
#define PDM_TRAJ_LEN {len(p['trajectory'])}
#define PDM_TRAJ_UNIT {p['trajectory_unit']}
#define PDM_DRIFT_LEN {len(p['drift_grid'])}
#define PDM_DRIFT_STEP 5
#define PDM_TRAJ_TRUE_RUL_END {p['trajectory_true_rul_end']}
// scalar constants are double literals; arrays are float32 in flash (virtual ESP32 mirrors both)
#define PDM_NOISE_SCALE_TRAJECTORY {p['noise_scale_trajectory']}
#define PDM_LIFE_LOG_MEAN {p['life_log_mean']}
#define PDM_LIFE_LOG_STD {p['life_log_std']}
#define PDM_LIFE_MIN {p['life_min']}

static const char* const PDM_CHANNELS[PDM_N_CHANNELS] = {{{names}}};
{_c_array("PDM_HEALTHY_MEAN", p["healthy_mean"])}
{_c_array("PDM_NOISE_SIGMA", p["noise_sigma"])}
{_c_array("PDM_DRIFT", flat_drift)}
{_c_array("PDM_TRAJECTORY", flat_traj)}
#endif  // {guard}
"""


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--profile", default="FD001", choices=["FD001", "FD003"])
    ap.add_argument("--unit", type=int, default=None)
    args = ap.parse_args(argv)
    p = build_profile(args.profile, args.unit)
    root = find_root() / "iot" / "esp32"
    (root / "include").mkdir(parents=True, exist_ok=True)
    name = args.profile.lower()
    (root / "include" / f"profile_{name}.h").write_text(render_header(p))
    (root / f"profile_{name}.json").write_text(json.dumps(p) + "\n")
    print(f"wrote iot/esp32/include/profile_{name}.h and iot/esp32/profile_{name}.json "
          f"(unit {p['trajectory_unit']}, {len(p['trajectory'])} cycles)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
